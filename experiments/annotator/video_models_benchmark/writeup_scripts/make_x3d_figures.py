"""Draw the X3D-M validation pilot figures and print the report's comparison table.

Reads the committed run histories, scores each run at its lowest-validation-loss
checkpoint and ranks configurations as the grid did. Figures reuse the MonoTrack
report's colours, axes and mean-with-seed-range dot plot.

Usage, from the repository root:
    python experiments/annotator/video_models_benchmark/writeup_scripts/make_x3d_figures.py

The shared test comparison is generated by ``make_videomae_figures.py``.
"""
from __future__ import annotations

import argparse
import gzip
import json
import sys
from dataclasses import dataclass
from pathlib import Path

import matplotlib

matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
from matplotlib.lines import Line2D
from matplotlib.patches import Patch
from matplotlib.ticker import FixedLocator, FuncFormatter, NullLocator

sys.path.insert(0, str(Path(__file__).resolve().parents[4]))

from experiments.annotator.monotrack_benchmark.writeup_scripts.make_figures import (
    ANNOTATOR_COLOUR,
    GRID,
    MONOTRACK_COLOUR,
    MUTED,
    SURFACE,
    TEXT,
    style_axes,
)

BENCHMARK = Path(__file__).resolve().parents[1]
RESULTS = BENCHMARK / 'results' / 'x3d_pilot'
FIGURES = BENCHMARK / 'writeup_figures'
TOLERANCE = '10'  # frames at 30 fps; the scorer scales it to each video's frame rate
ORIGINAL_UPDATES = 30_000
SCHEME_COLOURS = {'A': ANNOTATOR_COLOUR, 'B': MONOTRACK_COLOUR}
SCHEME_MARKERS = {'A': 'o', 'B': 's'}
SCHEME_LABELS = {
    'A': 'Positive centres ±1 frame',
    'B': 'Positive centres ±2 frames',
}
SEED_MARKERS = {0: 'o', 1: 's'}
X3D_COLOUR = '#7b52c9'
# The MonoTrack report's test population; X3D test scores must cover the same rallies.
TEST_RALLIES = 3327
TEST_CONTACTS = 37184
METRICS = (
    ('contact_f1', 'Contact F1 (%)\nhit found within ±10 frames'),
    ('correct_player_f1', 'Correct-player F1 (%)\nhit found and hitter right'),
    ('fully_correct_percent', 'Fully correct rallies (%)\nevery hit and hitter right, no extras'),
)
# The MonoTrack summary names the same three scores differently.
MONOTRACK_METRICS = {'contact_f1': 'f1', 'correct_player_f1': 'player_f1', 'fully_correct_percent': 'fully_correct'}


@dataclass(frozen=True)
class Run:
    name: str
    scheme: str
    contact_percent: int
    learning_rate: float
    seed: int
    history: list[dict]

    @property
    def selected(self) -> dict:
        # History is in update order and min keeps the first of equal values: earliest on a tie.
        return min(self.history, key=lambda check: check['validation']['loss'])


@dataclass(frozen=True)
class Configuration:
    scheme: str
    contact_percent: int
    learning_rate: float
    runs: tuple[Run, ...]  # one per seed, seed order

    @property
    def label(self) -> str:
        return f'{SCHEME_LABELS[self.scheme]}, {self.contact_percent}% contacts, LR {self.learning_rate:g}'

    def scores(self, metric: str) -> list[float]:
        return [run.selected['events'][TOLERANCE][metric] for run in self.runs]

    def mean(self, metric: str) -> float:
        return float(np.mean(self.scores(metric)))


@dataclass(frozen=True)
class DotRow:
    label: str
    colour: str
    marker: str
    scores: dict[str, list[float]]  # metric -> one score per seed


def read_json(path: Path) -> dict | list:
    with gzip.open(path, 'rt') as stream:
        return json.load(stream)


def sampling_scores(directory: Path, tolerance: str = TOLERANCE) -> dict[str, list[float]]:
    """Read the two selected checkpoints' stride-three scores."""
    records = [read_json(directory / f'seed{seed}' / 'scores.json.gz') for seed in (0, 1)]
    return {metric: [record['metrics'][tolerance][metric] for record in records] for metric, _title in METRICS}


def load_runs(results: Path) -> list[Run]:
    runs = []
    for directory in sorted(path for path in results.iterdir() if path.is_dir()):
        settings = read_json(directory / 'settings.json.gz')
        runs.append(Run(directory.name, settings['scheme'], round(100 * settings['contact_fraction']),
                        settings['learning_rate'], settings['seed'], read_json(directory / 'history.json.gz')))
    return runs


def rank_configurations(runs: list[Run]) -> list[Configuration]:
    """Group runs by setting, then order by mean fully correct rallies and mean correct-player F1."""
    groups: dict[tuple[str, int, float], list[Run]] = {}
    for run in runs:
        groups.setdefault((run.scheme, run.contact_percent, run.learning_rate), []).append(run)
    configurations = []
    for (scheme, contact_percent, learning_rate), members in groups.items():
        members.sort(key=lambda run: run.seed)
        if [run.seed for run in members] != [0, 1]:
            raise ValueError(f'{members[0].name}: expected seeds 0 and 1')
        configurations.append(Configuration(scheme, contact_percent, learning_rate, tuple(members)))
    return sorted(configurations, key=lambda configuration: (-configuration.mean('fully_correct_percent'),
                                                             -configuration.mean('correct_player_f1')))


def validation_population(runs: list[Run]) -> tuple[int, int]:
    """Rally and labelled-hit counts, which must be the same for every run."""
    counts = {(run.selected['events'][TOLERANCE]['rallies'], run.selected['events'][TOLERANCE]['labelled'])
              for run in runs}
    if len(counts) != 1:
        raise ValueError(f'runs were scored on different validation populations: {counts}')
    return counts.pop()


def print_table(configurations: list[Configuration]) -> None:
    print('| Rank | Configuration | Fully correct rallies (%), seed 0 / 1 / mean '
          '| Correct-player F1 (%), seed 0 / 1 / mean | Contact F1 (%), mean | Selected checkpoints |')
    print('|---:|---|---:|---:|---:|---|')
    for rank, configuration in enumerate(configurations, start=1):
        cells = []
        for metric in ('fully_correct_percent', 'correct_player_f1'):
            seed0, seed1 = configuration.scores(metric)
            cells.append(f'{seed0:.1f} / {seed1:.1f} / **{configuration.mean(metric):.1f}**')
        steps = ' / '.join(f"{run.selected['steps'] // 1000}k" for run in configuration.runs)
        print(f'| {rank} | {configuration.label} | {cells[0]} | {cells[1]} '
              f"| {configuration.mean('contact_f1'):.1f} | {steps} |")


def dot_plot(rows: list[DotRow], title: str, notes: tuple[str, ...], out: Path,
             row_separators: tuple[int, ...] = ()) -> None:
    """The MonoTrack headline layout: one row per system, mean dot, black line across the seed range."""
    figure, axes_row = plt.subplots(1, 3, figsize=(13, 1.6 + 0.62 * len(rows)), sharey=True, facecolor=SURFACE)
    positions = np.arange(len(rows))[::-1].astype(float)
    for axes, (metric, metric_title) in zip(axes_row, METRICS, strict=True):
        low = min(min(row.scores[metric]) for row in rows) - 2
        high = max(max(row.scores[metric]) for row in rows) + 2
        style_axes(axes)
        for position, row in zip(positions, rows, strict=True):
            mean = float(np.mean(row.scores[metric]))
            axes.plot([low, mean], [position, position], color=GRID, linewidth=1.5, zorder=1)
            axes.plot([min(row.scores[metric]), max(row.scores[metric])], [position, position], color=TEXT,
                      linewidth=1.6, zorder=2)
            axes.scatter(mean, position, s=90, color=row.colour, marker=row.marker, zorder=3, linewidth=1.5,
                         edgecolor=SURFACE)
            axes.annotate(f'{mean:.1f}', (max(row.scores[metric]), position), xytext=(9, 0),
                          textcoords='offset points', va='center', fontsize=10, color=TEXT)
        axes.set_xlim(low, high + 2.5)
        axes.set_ylim(positions.min() - 0.6, positions.max() + 0.6)
        axes.set_title(metric_title, fontsize=11, color=TEXT, loc='left')
    axes_row[0].set_yticks(positions, [row.label for row in rows], fontsize=10)
    figure.suptitle(title, fontsize=13, color=TEXT, x=0.01, ha='left')
    note_height = 0.26 / (1.6 + 0.62 * len(rows))  # about 0.26 inches per line of notes
    for index, note in enumerate(reversed(notes)):
        figure.text(0.01, 0.012 + index * note_height, note, fontsize=9, color=MUTED)
    figure.tight_layout(rect=(0, 0.012 + len(notes) * note_height, 1, 0.94))
    for after_row in row_separators:
        boundary = len(rows) - after_row - 0.5
        display_point = axes_row[0].transData.transform((0, boundary))
        figure_y = figure.transFigure.inverted().transform(display_point)[1]
        figure.add_artist(Line2D([0.01, axes_row[-1].get_position().x1], [figure_y, figure_y],
                                 transform=figure.transFigure, color=MUTED, linewidth=1, linestyle=(0, (2, 3))))
    figure.savefig(out, dpi=150, facecolor=SURFACE)
    plt.close(figure)


def configuration_figure(configurations: list[Configuration], rallies: int, contacts: int,
                          stride_scores: dict[str, list[float]], out: Path) -> None:
    selected = configurations[0]
    ordered = sorted(configurations, key=lambda config: (config.scheme, config.contact_percent, config.learning_rate))
    rows = [DotRow(configuration.label + (' (selected)' if configuration == selected else ''),
                   SCHEME_COLOURS[configuration.scheme], SCHEME_MARKERS[configuration.scheme],
                   {metric: configuration.scores(metric) for metric, _title in METRICS})
            for configuration in ordered]
    rows.append(DotRow('Selected configuration, stride 3 (offset 0)', X3D_COLOUR, 'D', stride_scores))
    notes = (
        'First six rows: stride 1 (every frame). Last row: native stride 3, offset 0. All use enforced alternation.',
        ('Each run is scored at its lowest-validation-loss checkpoint. Dots: mean of seeds 0 and 1; '
         'black lines join the two seeds.'),
        ('Given rally bounds; contact tolerance ±10 frames at 30 fps. '
         'With ±1-frame positives, distance-two centres are ignored.'),
    )
    dot_plot(rows, f'X3D-M validation pilot: 8 videos, {rallies:,} rallies, {contacts:,} labelled hits', notes,
             out / 'fig1_configurations.png',
             row_separators=(sum(config.scheme == 'A' for config in ordered), len(ordered)))


def loss_columns(configurations: list[Configuration]) -> dict[tuple[str, int, float], tuple[int, int]]:
    """Group columns by contact proportion and learning rate; align the two positive-centre windows."""
    scheme_a = sorted((configuration for configuration in configurations if configuration.scheme == 'A'),
                       key=lambda config: (config.contact_percent, config.learning_rate))
    column_of_setting = {(configuration.contact_percent, configuration.learning_rate): column
                         for column, configuration in enumerate(scheme_a)}
    cells = {}
    for configuration in configurations:
        setting = (configuration.contact_percent, configuration.learning_rate)
        row = 0 if configuration.scheme == 'A' else 1
        cells[(configuration.scheme, *setting)] = (row, column_of_setting[setting])
    return cells


def loss_figure(configurations: list[Configuration], out: Path) -> None:
    cells = loss_columns(configurations)
    columns = max(column for _row, column in cells.values()) + 1
    figure, axes_grid = plt.subplots(2, columns, figsize=(13, 6.8), sharex=True, facecolor=SURFACE)
    last_step = max(check['steps'] for configuration in configurations for run in configuration.runs
                    for check in run.history)
    used = set(cells.values())
    for configuration in configurations:
        axes = axes_grid[cells[(configuration.scheme, configuration.contact_percent, configuration.learning_rate)]]
        style_axes(axes, 'both')
        axes.axvspan(ORIGINAL_UPDATES, last_step + 2500, color=GRID, alpha=0.6, linewidth=0, zorder=0)
        colour = SCHEME_COLOURS[configuration.scheme]
        for run in configuration.runs:
            steps = [check['steps'] for check in run.history]
            marker = SEED_MARKERS[run.seed]
            axes.plot(steps, [check['train_loss'] for check in run.history], color=colour, linestyle='--',
                      linewidth=1.2, marker=marker, markersize=3.5, markerfacecolor=SURFACE, alpha=0.75)
            axes.plot(steps, [check['validation']['loss'] for check in run.history], color=colour, linewidth=1.8,
                      marker=marker, markersize=4.5)
            axes.scatter(run.selected['steps'], run.selected['validation']['loss'], s=150, facecolor='none',
                         edgecolor=TEXT, linewidth=1.5, zorder=4)
        steps = ' / '.join(f"{run.selected['steps'] // 1000}k" for run in configuration.runs)
        axes.set_title(f'{configuration.contact_percent}% contacts, LR {configuration.learning_rate:g}\n'
                       f'selected {steps}', fontsize=10, color=TEXT, loc='left')
    # Log scale keeps the early high losses in view without flattening the later differences.
    for row in range(2):
        row_axes = [axes_grid[row, column] for column in range(columns) if (row, column) in used]
        low = min(axes.dataLim.y0 for axes in row_axes) * 0.92
        high = max(axes.dataLim.y1 for axes in row_axes) * 1.08
        for axes in row_axes:
            axes.set_yscale('log')
            axes.set_ylim(low, high)
            axes.yaxis.set_major_locator(FixedLocator([0.1, 0.15, 0.2, 0.3, 0.4, 0.5]))
            axes.yaxis.set_minor_locator(NullLocator())
            axes.yaxis.set_major_formatter(FuncFormatter(lambda loss, _position: f'{loss:g}'))
        row_axes[0].set_ylabel('Cross-entropy (log scale)', color=TEXT)
        scheme = 'A' if row == 0 else 'B'
        heading = row_axes[0].annotate(SCHEME_LABELS[scheme], (0, 1), xycoords='axes fraction', xytext=(0, 34),
                                       textcoords='offset points', fontsize=11, fontweight='bold', color=TEXT)
        # The heading spans several panels; counting it in the layout would push the columns apart.
        heading.set_in_layout(False)
    for row in range(2):
        for column in range(columns):
            axes = axes_grid[row, column]
            if (row, column) not in used:
                axes.set_visible(False)
            elif row == 1 or (1, column) not in used:
                axes.set_xlabel('Updates', color=TEXT)
                axes.tick_params(labelbottom=True)
            axes.xaxis.set_major_formatter(FuncFormatter(lambda step, _position: f'{step / 1000:g}k'))
    axes_grid[0, 0].set_xlim(0, last_step + 2500)
    handles = [
        Line2D([], [], color=MUTED, linewidth=1.8, label='Validation loss: whole validation rallies'),
        Line2D([], [], color=MUTED, linewidth=1.2, linestyle='--',
               label='Training loss: mean since the previous check'),
        Line2D([], [], color=MUTED, marker='o', linestyle='none', label='Seed 0'),
        Line2D([], [], color=MUTED, marker='s', linestyle='none', label='Seed 1'),
        Line2D([], [], color=TEXT, marker='o', markersize=11, markerfacecolor='none', linestyle='none',
               label='Selected checkpoint: lowest validation loss'),
        Patch(color=GRID, alpha=0.6, label=f'Continuation after {ORIGINAL_UPDATES // 1000}k updates'),
    ]
    figure.suptitle('X3D-M pilot: training and validation loss for all 12 runs', fontsize=13, color=TEXT,
                    x=0.01, ha='left')
    figure.tight_layout(rect=(0, 0, 1, 0.95), h_pad=3.2)
    # The legend and notes fill the bottom-row cells that scheme B leaves empty.
    empty = [axes_grid[1, column] for column in range(columns) if (1, column) not in used]
    left, top = empty[0].get_position().x0, empty[0].get_position().y1
    figure.legend(handles=handles, loc='upper left', bbox_to_anchor=(left, top), frameon=False, fontsize=9.5)
    figure.text(left, 0.03, 'Panel titles give the selected update for seed 0, then seed 1.\n'
                'Compare losses within a row: the positive windows label\n'
                'different frames as contacts. Training batches hold 25% or 50%\n'
                "contact clips; validation keeps the rallies' natural contact rate,\n"
                'so training and validation loss levels are not directly comparable.',
                fontsize=9, color=MUTED, va='bottom', linespacing=1.5)
    figure.savefig(out / 'fig2_loss_curves.png', dpi=150, facecolor=SURFACE)
    plt.close(figure)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--results', type=Path, default=RESULTS)
    parser.add_argument('--out', type=Path, default=FIGURES)
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    runs = load_runs(args.results)
    configurations = rank_configurations(runs)
    rallies, contacts = validation_population(runs)
    print_table(configurations)
    stride_scores = sampling_scores(args.results.parent / 'x3d_stride3' / 'validation')
    configuration_figure(configurations, rallies, contacts, stride_scores, args.out)
    loss_figure(configurations, args.out)


if __name__ == '__main__':
    main()
